"""Advance only using measured gate evidence. Missing evidence always leaves a gate closed."""
import argparse,hashlib,json
import torch
from pathlib import Path
from .collect import atomic_json
from .evaluate import paired_gate

def read(path):return json.loads(path.read_text())

def assess(candidate,reference,data_dir,objective):
    report=dict(version=2,objective=objective,ppo_allowed=False,gates={})
    manifest=read(data_dir/'manifest.json');reference_skills=read(reference/'skills/results.json')['aggregate']
    skills=read(candidate/'skills/results.json')['aggregate'];metrics=torch.load(candidate/'bc/best.pt',map_location='cpu',weights_only=False)['validation']
    coverage=manifest['unique_layouts']>=1000 and manifest['actual_emissions']>=20000
    report['gates']['coverage']=dict(passed=coverage,unique_layouts=manifest['unique_layouts'],actual_emissions=manifest['actual_emissions'])
    passed_skills={s:bool(skills[s]['rounds']>=50 and skills[s]['success']>=.9*reference_skills[s]['success'] and
        reference_skills[s]['success']>=.9 and skills[s]['suicides']<=.02 and (s!='muzzle' or skills[s]['fizzles']<=.02)) for s in reference_skills}
    report['gates']['G1']=dict(passed=all(passed_skills.values()),skills=passed_skills,measured=skills,reference=reference_skills)
    report['gates']['G2']=dict(passed=bool(metrics['fire_recall']>=.8 and metrics['fire_precision']>=.7 and metrics['fire_positive']>=200),
        fire_recall=metrics['fire_recall'],fire_precision=metrics['fire_precision'],heldout_actual_fire_positive=metrics['fire_positive'])
    if (candidate/'combat/results.json').exists():
        report['gates']['G3']=paired_gate(read(candidate/'combat/results.json')['rows'],read(reference/f'{objective}/results.json')['rows'],objective)
    else:report['gates']['G3']=dict(passed=False,reason='combat_acceptance_not_run')
    # G0 is generated by the executable pipeline, never assumed from a checkpoint filename.
    g0=read(candidate.parent/'G0.json') if (candidate.parent/'G0.json').exists() else {'passed':False}
    report['gates']['G0']=g0
    report['ppo_allowed']=bool(g0['passed'] and all(g['passed'] for g in report['gates'].values()))
    model=candidate/'bc/best.pt'
    report['model_sha256']=hashlib.sha256(model.read_bytes()).hexdigest() if model.exists() else None
    return report

def main():
    p=argparse.ArgumentParser();p.add_argument('--candidate',type=Path,required=True);p.add_argument('--reference',type=Path,required=True)
    p.add_argument('--data',type=Path,required=True);p.add_argument('--objective',choices=['win','frag'],required=True)
    a=p.parse_args();report=assess(a.candidate,a.reference,a.data,a.objective);atomic_json(a.candidate/'gates.json',report);print(json.dumps(report),flush=True)

if __name__=='__main__':main()
